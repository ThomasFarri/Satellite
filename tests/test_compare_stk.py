"""Tests for validation/compare_stk.py using an obviously SYNTHETIC fixture.

The fixture is generated here from this tool's own output with known offsets
added, written in STK's CSV layout. It is not STK data and only proves that the
comparison script parses the format and measures residuals correctly.
"""

import importlib.util
from dataclasses import replace

import numpy as np
import pytest

from opticalpass.frames import Station, times_from_epoch
from opticalpass.geometry import Tracker
from opticalpass.passes import find_passes
from opticalpass.propagators import SGP4Propagator
from tests.conftest import ROOT

spec = importlib.util.spec_from_file_location("compare_stk", ROOT / "validation" / "compare_stk.py")
compare_stk = importlib.util.module_from_spec(spec)
spec.loader.exec_module(compare_stk)

OFFSET_S = 0.3
OFFSET_EL_DEG = 0.002


def _stk_time(t):
    dt = t.to_datetime()
    return dt.strftime("%d %b %Y %H:%M:%S.") + f"{dt.microsecond // 1000:03d}"


@pytest.fixture(scope="module")
def fixture_files(tmp_path_factory, example_config):
    cfg = example_config
    tle = ROOT / "validation" / "stk" / "satellite.tle"
    l1, l2 = [ln for ln in tle.read_text().splitlines() if ln.startswith(("1 ", "2 "))]
    tr = Tracker(SGP4Propagator.from_tle(l1, l2, cfg.epoch), Station.from_config(cfg.station))
    geo = replace(cfg.constraints, night_only=False, min_sun_separation_rad=0.0)
    passes = find_passes(tr, geo, 0.0, 86400.0)
    d = tmp_path_factory.mktemp("synthetic_stk")
    acc = d / "SYNTHETIC_access_TEST_ONLY.csv"
    lines = ["# SYNTHETIC TEST FIXTURE: generated by tests, not STK output",
             '"Access","Start Time (UTCG)","Stop Time (UTCG)","Duration (sec)"']
    for k, p in enumerate(passes, 1):
        t = times_from_epoch(cfg.epoch, [p.start_s - OFFSET_S, p.end_s - OFFSET_S])
        lines.append(f'{k},"{_stk_time(t[0])}","{_stk_time(t[1])}",{p.duration_s:.3f}')
    lines.append('"Min Duration",,,1.0')
    acc.write_text("\n".join(lines) + "\n")
    aer = d / "SYNTHETIC_aer_TEST_ONLY.csv"
    ts = np.concatenate([np.arange(p.start_s, p.end_s, 10.0) for p in passes])
    g = tr.geometry(ts)
    tt = times_from_epoch(cfg.epoch, ts)
    rows = ["# SYNTHETIC TEST FIXTURE: generated by tests, not STK output",
            '"Time (UTCG)","Azimuth (deg)","Elevation (deg)","Range (km)"']
    for k in range(ts.size):
        rows.append(f'"{_stk_time(tt[k])}",{np.degrees(g.az_rad[k]):.6f},'
                    f'{np.degrees(g.el_rad[k]) - OFFSET_EL_DEG:.6f},{g.range_m[k] / 1e3:.6f}')
    aer.write_text("\n".join(rows) + "\n")
    return acc, aer, tle


def test_compare_recovers_known_offsets(fixture_files, tmp_path):
    acc, aer, tle = fixture_files
    res = compare_stk.compare(acc, aer, tle, tmp_path)
    # Times are written to 1 ms in the STK format, so allow 2 ms.
    assert res["max_rise_set_diff_s"] == pytest.approx(OFFSET_S, abs=2e-3)
    # The AER times are rounded to 1 ms too, which moves elevation by up to
    # about 1 deg/s * 0.5 ms = 5e-4 deg on high passes.
    assert res["max_el_diff_deg"] == pytest.approx(OFFSET_EL_DEG, abs=1e-3)
    assert (tmp_path / "stk_residuals.png").is_file()
    assert (tmp_path / "stk_access_residuals.csv").is_file()


def test_parse_stk_time_formats():
    t = compare_stk.parse_stk_time("1 Mar 2027 06:25:20.028")
    assert t.isot == "2027-03-01T06:25:20.028"
    assert compare_stk.parse_stk_time("2027-03-01T06:25:20.028") == t
    with pytest.raises(ValueError):
        compare_stk.parse_stk_time("yesterday")



def test_missing_file(tmp_path):
    with pytest.raises(FileNotFoundError):
        compare_stk.read_access(tmp_path / "nope.csv")
